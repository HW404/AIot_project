"""
라파 게임 엔진 설정

실행 환경에 따라 수정 필요한 값들:
  - SERIAL_PORT: 아두이노가 꽂힌 USB 포트
  - SERVER_HOST: 노트북(서버)의 IP 주소
  - CDS_*_THRESHOLD: 실제 환경의 밝기/어둠 측정값 보고 조정
"""

# ============================================================
# 시리얼 (아두이노)
# ============================================================
# 라파의 USB-아두이노 포트
#   - Uno R3 정품:    /dev/ttyACM0 (보통)
#   - CH340 호환보드: /dev/ttyUSB0 (보통)
#   - 실행 시 자동 감지 폴백 있음
SERIAL_PORT = "/dev/ttyACM0"
SERIAL_BAUDRATE = 9600

# ============================================================
# TCP (노트북 서버)
# ============================================================
SERVER_HOST = "192.168.0.10"   # ★ 노트북 IP - 실제 IP로 변경 필수!
SERVER_PORT = 9000
RECONNECT_INTERVAL = 3.0       # 연결 끊기면 N초 후 재시도

# ============================================================
# 퍼즐 임계값 (게임 룰)
# ============================================================
# CDS (조도) - 손전등 ON/OFF
# ⚠️ CDS 회로 구성에 따라 값 방향이 반대일 수 있음:
#   - 분압 구성 (VCC-CDS-A0-10K-GND): 밝을수록 값 ↑ (이 코드의 기본 가정)
#   - 반대 구성 (VCC-10K-A0-CDS-GND): 밝을수록 값 ↓
# 실제 측정해보고 조정 필수.
# 예) 평상시 600, 손전등 비추면 950이면 → ON=850, OFF=700 정도
# 예) 평상시 950, 손전등 비추면 100이면 → 비교 부등호 반대로 변경 필요
CDS_FLASHLIGHT_ON_THRESHOLD = 800    # 이 값 이상이면 빛 감지 (손전등 ON)
CDS_FLASHLIGHT_OFF_THRESHOLD = 300   # 이 값 이하면 빛 사라짐
# 히스테리시스(ON/OFF 차이): 경계값 근처에서 깜빡임 방지

# 온도 (전력 복구 퍼즐)
TEMP_POWER_RESTORE_THRESHOLD = 30.0  # 이 온도 이상 도달하면 전력 복구

# ============================================================
# 디버그
# ============================================================
